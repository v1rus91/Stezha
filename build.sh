#!/bin/zsh
# Builds Стежа.app and installs it into /Applications.
set -e
cd "$(dirname "$0")"
export DEVELOPER_DIR=/Applications/Xcode.app/Contents/Developer
# The shared alerts.in.ua key lives in .apikey (gitignored) or $STEZHA_API_KEY and is baked in here.
KEY="${STEZHA_API_KEY:-$(cat .apikey 2>/dev/null)}"
printf '// Generated by build.sh — do not commit.\nenum Secrets {\n    static let alertsKey = "%s"\n}\n' "$KEY" > Sources/Stezha/Secrets.swift
swift build -c release
APP="build/Стежа.app"
rm -rf "$APP"; mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources/uk.lproj" "$APP/Contents/Resources/en.lproj"
cp .build/release/Stezha "$APP/Contents/MacOS/Stezha"
cp Resources/Info.plist "$APP/Contents/Info.plist"
cp Resources/oblasts.json "$APP/Contents/Resources/"
if [[ ! -f Resources/AppIcon.icns ]]; then
  T=$(mktemp -d); swift scripts/icon.swift Resources/oblasts.json "$T/icon.png"
  mkdir "$T/AppIcon.iconset"
  for s in 16 32 128 256 512; do
    sips -z $s $s "$T/icon.png" --out "$T/AppIcon.iconset/icon_${s}x${s}.png" >/dev/null
    sips -z $((s*2)) $((s*2)) "$T/icon.png" --out "$T/AppIcon.iconset/icon_${s}x${s}@2x.png" >/dev/null
  done
  iconutil -c icns "$T/AppIcon.iconset" -o Resources/AppIcon.icns
fi
cp Resources/AppIcon.icns "$APP/Contents/Resources/"
codesign --force --deep --sign - "$APP"
pkill -x Stezha 2>/dev/null || true
rm -rf "/Applications/Стежа.app"; cp -R "$APP" /Applications/
echo "Installed /Applications/Стежа.app"
